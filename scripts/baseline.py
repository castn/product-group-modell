"""Measures the app's dictionary as the baseline (step 7).

Calls the Kotlin baseline (kotlin/baseline, builds the code from kotlin/app-snapshot):
    cd kotlin && ./gradlew :baseline:installDist

Evaluated on
- the real receipts (data/eval/item-groups.csv: receipt;name;class, the group
  follows from mapping/classes.yaml; older files with a group column work too)
- the German product names from Open Food Facts etc. with the group from the
  category mapping (data/interim/de_labeled.parquet). These names are cleanly
  written, not in receipt style; so the value rather shows how much vocabulary
  the dictionary covers.

Coverage = share with a suggestion, accuracy = share correct among the suggestions.

Usage:  uv run scripts/baseline.py
"""

import subprocess
import sys
from collections import Counter
from pathlib import Path

import polars as pl

from pgm.categories import class_groups

ROOT = Path(__file__).resolve().parent.parent
BIN = (
    ROOT / "kotlin" / "baseline" / "build" / "install" / "baseline" / "bin" / "baseline"
)
EVAL = ROOT / "data" / "eval" / "item-groups.csv"
LABELED = ROOT / "data" / "interim" / "de_labeled.parquet"
REPORT = ROOT / "reports" / "baseline.md"

# Merchants of the receipts whose photo is cropped to the items (as in the app's test)
MERCHANTS = {
    "dm": "dm-drogerie markt",
    "metzger": "Metzgerei",
    "baecker": "Bäckerei",
    "baumarkt": "Baumarkt",
}
# Discount lines: assigned to the item above by a rule in the app, not the model's task
DISCOUNTS = {"Preisänderung", "Feigen 1 Euro"}


def classify(rows: list[tuple[str, str | None]]) -> list[tuple[str | None, str | None]]:
    if not BIN.exists():
        raise SystemExit("first: cd kotlin && ./gradlew :baseline:installDist")
    data = "".join(
        f"{name.replace(chr(9), ' ').replace(chr(10), ' ')}\t{merchant or ''}\n"
        for name, merchant in rows
    )
    out = subprocess.run(
        [str(BIN)], input=data, capture_output=True, text=True, check=True
    ).stdout
    result = []
    for line in out.splitlines():
        group, source = line.split("\t")
        result.append((group or None, source or None))
    assert len(result) == len(rows)
    return result


def metrics(expected: list[str], predicted: list[str | None]) -> tuple[int, int, int]:
    total = len(expected)
    assigned = sum(p is not None for p in predicted)
    correct = sum(p == e for p, e in zip(predicted, expected, strict=True))
    return total, assigned, correct


def fmt(total: int, assigned: int, correct: int) -> str:
    cov = 100 * assigned / total if total else 0
    acc = 100 * correct / assigned if assigned else 0
    return f"| {total:,} | {assigned:,} ({cov:.0f} %) | {correct:,} | {acc:.0f} % |"


def main() -> None:
    lines = ["# Baseline: the app's dictionary", ""]
    lines += [
        "Generated by `scripts/baseline.py`. Coverage = share with a suggestion,",
        "accuracy = share correct among the suggestions.",
        "",
        "| Data | Variant | Rows | with suggestion | correct | Accuracy |",
        "|---|---|---:|---:|---:|---:|",
    ]

    receipts = pl.read_csv(EVAL, separator=";").filter(~pl.col("name").is_in(DISCOUNTS))
    rows = [
        (name, MERCHANTS.get(receipt, receipt))
        for receipt, name in zip(receipts["receipt"], receipts["name"], strict=True)
    ]
    if "class" in receipts.columns:
        groups = class_groups()
        expected = [groups[c] for c in receipts["class"]]
    else:
        expected = receipts["group"].to_list()
    result = classify(rows)
    dictionary_only = [g if s == "DICTIONARY" else None for g, s in result]
    with_merchant = [g for g, _ in result]
    lines.append(
        "| Receipts | dictionary only | " + fmt(*metrics(expected, dictionary_only))[2:]
    )
    lines.append(
        "| Receipts | dictionary + merchant | "
        + fmt(*metrics(expected, with_merchant))[2:]
    )
    errors = [
        f"- `{r}`: {name} → {g or '–'} ({s or '–'}), expected {e}"
        for (name, _), (g, s), e, r in zip(
            rows, result, expected, receipts["receipt"], strict=True
        )
        if g != e
    ]

    labeled = pl.read_parquet(LABELED).filter(pl.col("group").is_not_null())
    off_result = classify([(n, None) for n in labeled["name_de"]])
    off_pred = [g for g, _ in off_result]
    off_expected = labeled["group"].to_list()
    lines.append(
        "| Open Food Facts etc. (DE) | dictionary only | "
        + fmt(*metrics(off_expected, off_pred))[2:]
    )

    lines += ["", "## Per item group (Open Food Facts etc.)", ""]
    lines += [
        "| Group | Rows | with suggestion | correct | Accuracy |",
        "|---|---:|---:|---:|---:|",
    ]
    by_group: dict[str, list] = {}
    for e, p in zip(off_expected, off_pred, strict=True):
        by_group.setdefault(e, []).append(p)
    for group, preds in sorted(by_group.items()):
        lines.append(f"| {group} " + fmt(*metrics([group] * len(preds), preds)))

    confusions = Counter(
        (e, p) for e, p in zip(off_expected, off_pred, strict=True) if p and p != e
    )
    lines += ["", "## Most frequent confusions (Open Food Facts etc.)", ""]
    lines += ["| expected | suggested | count |", "|---|---|---:|"]
    lines += [f"| {e} | {p} | {n:,} |" for (e, p), n in confusions.most_common(15)]

    lines += ["", "## Errors on the receipts", "", *errors]
    REPORT.write_text("\n".join(lines) + "\n")
    print(f"→ {REPORT.relative_to(ROOT)}", file=sys.stderr)


if __name__ == "__main__":
    main()
